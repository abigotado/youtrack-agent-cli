// Command gencontract renders the stable machine contract from internal/errx.
package main

import (
	"fmt"
	"strings"

	"github.com/abigotado/youtrack-agent-cli/internal/errx"
	"github.com/abigotado/youtrack-agent-cli/internal/oauthrecovery"
)

const generatedNotice = "<!-- Code generated by tools/gencontract. DO NOT EDIT. -->"

func renderMarkdown(contract errx.Contract) string {
	var output strings.Builder
	profileRequired := errx.ProfileRequired()
	output.WriteString(generatedNotice)
	output.WriteString("\n\n# Machine contract\n\n")
	output.WriteString("Regenerate with `go generate ./...`.\n\n")
	output.WriteString("## Envelope\n\n")
	_, _ = fmt.Fprintf(&output, "Current version: `%d`.\n\n", contract.EnvelopeVersion)
	output.WriteString("```json\n")
	_, _ = fmt.Fprintf(&output, `{"ok":true,"v":%d,"data":[{"id":"APP-123","summary":"Example"}],"meta":{"count":1,"truncated":true,"next_cursor":"opaque","profile":"work","instance":"https://example.youtrack.cloud"}}`, contract.EnvelopeVersion)
	output.WriteByte('\n')
	_, _ = fmt.Fprintf(&output, `{"ok":false,"v":%d,"error":{"code":%q,"message":%q},"hint":%q}`, contract.EnvelopeVersion, profileRequired.Reason, profileRequired.Message, profileRequired.Hint)
	output.WriteString("\n```\n\n")
	output.WriteString("The top-level keys `ok`, `v`, `data`, `meta`, `error`, and `hint` are the\n")
	_, _ = fmt.Fprintf(&output, "v%d vocabulary. A field rename, removal, or type change requires an envelope\n", contract.EnvelopeVersion)
	output.WriteString("version bump. Optional `meta` fields are `count`, `truncated`, `next_cursor`,\n")
	output.WriteString("`profile`, `instance`, `account_id`, and `account_login`; metadata never contains credentials.\n\n")
	output.WriteString("stdout receives exactly one compact JSON envelope in JSON mode. Diagnostics,\n")
	output.WriteString("prompts, warnings, and logs go to stderr. `error.code` is a stable\n")
	output.WriteString("`SCREAMING_SNAKE_CASE` value; add error detail there before considering a new\n")
	output.WriteString("process status.\n\n")
	output.WriteString("## OAuth token errors (standard macOS CLI; planned v0.2.0)\n\n")
	output.WriteString("These codes are planned for the tagged v0.2.0 Formula. An untagged source checkout\n")
	output.WriteString("reports `devel`; merged source alone is not a Homebrew release. Check the\n")
	output.WriteString("installed binary's version before relying on this table.\n\n")
	output.WriteString("Authorization-code exchange failures previously used\n")
	output.WriteString("`OAUTH_TOKEN_EXCHANGE_FAILED` / exit 5. The JSON envelope remains v1, but\n")
	output.WriteString("the following recovery codes are a deliberate breaking change.\n\n")
	output.WriteString("| `error.code` | Exit | Recovery |\n")
	output.WriteString("| --- | ---: | --- |\n")
	for _, descriptor := range oauthrecovery.Catalog() {
		_, _ = fmt.Fprintf(&output, "| `%s` | %d | %s |\n", descriptor.Reason, descriptor.Exit, descriptor.Recovery)
	}
	output.WriteByte('\n')
	output.WriteString("Cancellation or deadline detected before a token request attempt retains\n")
	output.WriteString("normal cancellation/timeout recovery. Once an attempt begins, dispatch\n")
	output.WriteString("may be uncertain: interrupted code exchange requires a fresh login, and\n")
	output.WriteString("refresh failures keep the published code and exit in v0.2.0, including\n")
	output.WriteString("DNS/TLS failures and local failure after successful refresh. Local binding\n")
	output.WriteString("rejection happens before Save and leaves the old credential in place; a\n")
	output.WriteString("Save error leaves persisted credential state unknown. The server\n")
	output.WriteString("may have rotated the old refresh token before its response was lost.\n")
	output.WriteString("Public recovery hints identify fixed local repair for binding or token validation\n")
	output.WriteString("and for Keychain interaction, ACL, cancellation, timeout, availability, or other\n")
	output.WriteString("store failures; they never expose raw errors or OSStatus. An HTTP 200 token-body\n")
	output.WriteString("read error is non-retryable after authorization-code exchange because the code\n")
	output.WriteString("may already have been consumed.\n")
	output.WriteString("For refresh, local binding or token validation failures, Keychain interaction,\n")
	output.WriteString("ACL or status failures, context cancellation or deadline, and unknown local\n")
	output.WriteString("store failures all collapse to `OAUTH_TOKEN_EXCHANGE_FAILED` / exit 5.\n")
	output.WriteString("Hints describe an applicable local repair in prose; their wording is not a\n")
	output.WriteString("stable machine ID. Consumers branch on `error.code` and exit, not hint text.\n")
	output.WriteString("Malformed or oversized HTTP 200 and unexpected 1xx or non-200 2xx responses\n")
	output.WriteString("also do not prove the old authorization code remains usable. Always obtain a\n")
	output.WriteString("new code in a fresh interactive login; never replay that token POST.\n")
	output.WriteString("The CLI makes no repeat attempt within\n")
	output.WriteString("one invocation. Failed token requests leave the old credential in place.\n")
	output.WriteString("A later auth-dependent invocation, including `auth status --check` or a\n")
	output.WriteString("read, may automatically retry the old token. Agents must avoid those commands\n")
	output.WriteString("until a fresh interactive login. The operator must explicitly approve\n")
	output.WriteString("replacement if the old credential remains (`auth login --profile NAME --yes`);\n")
	output.WriteString("agents must not add `--yes` automatically. A durable cross-process refresh fence\n")
	output.WriteString("is deferred. OAuth token errors do not publish `error.retry_after`;\n")
	output.WriteString("for endpoint unavailability, use caller-bounded backoff and a fresh login.\n")
	output.WriteString("See the [detailed OAuth recovery guide](https://github.com/abigotado/youtrack-agent-cli/blob/main/docs/oauth-errors.md).\n\n")
	output.WriteString("## JSON response recovery\n\n")
	output.WriteString("Apply this grammar in order:\n\n")
	output.WriteString("1. A v1 envelope is exactly one complete top-level JSON object followed only by\n")
	output.WriteString("   whitespace. It requires boolean `ok` and a JSON integer `v` whose value is\n")
	output.WriteString("   exactly `1`. Decimal, exponent, string, null, boolean, and every other\n")
	output.WriteString("   version representation is unsupported. If `ok` is `true`, `data` must be\n")
	output.WriteString("   present and non-null; `error` and `hint` must be absent, and their presence\n")
	output.WriteString("   is invalid even when `null`. If `ok` is `false`, `data` must be absent;\n")
	output.WriteString("   `error` must be a present non-null object with string `code` and `message`,\n")
	output.WriteString("   and `hint` must be a present string. Forbidden-key presence is invalid even\n")
	output.WriteString("   when `null`. `meta` is optional; unknown additive fields are tolerated. They\n")
	output.WriteString("   never repair an invalid known member. On either branch, `meta` may be absent;\n")
	output.WriteString("   when present it must be a non-null object and may be empty. Every present\n")
	output.WriteString("   known metadata member must\n")
	output.WriteString("   be non-null and have its exact v1 type: `count` is a nonnegative JSON integer\n")
	output.WriteString("   written without a fraction or exponent, `truncated` is boolean, and\n")
	output.WriteString("   `next_cursor`, `profile`, `instance`, `account_id`, and `account_login` are strings. Unknown additive metadata\n")
	output.WriteString("   members are tolerated, but they never repair a missing, null, or wrongly\n")
	output.WriteString("   typed known member. A malformed `meta` makes the entire envelope invalid. A\n")
	output.WriteString("   valid v1 envelope is the primary result; never replace it with stderr. Any\n")
	output.WriteString("   malformed or unsupported envelope\n")
	output.WriteString("   makes stdout invalid.\n\n")
	output.WriteString("   Valid v1 examples:\n\n")
	output.WriteString("   `{" + `"ok":true,"v":1,"data":{},"meta":{},"future":true` + "}`\n\n")
	output.WriteString("   `{" + `"ok":false,"v":1,"error":{"code":"PROFILE_REQUIRED","message":"profile is required","future":true},"hint":"pass --profile","meta":{"count":0,"truncated":false,"next_cursor":"","profile":"work","instance":"https://example.youtrack.cloud","future":null},"future":true` + "}`\n\n")
	output.WriteString("   Invalid examples:\n\n")
	output.WriteString("   - `{" + `"ok":true,"v":2,"data":{}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1.0,"data":{}` + "}`\n")
	output.WriteString("   - `{" + `"ok":"true","v":1,"data":{}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":"1","data":{}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":null` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"error":null` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"hint":null` + "}`\n")
	output.WriteString("   - `{" + `"ok":false,"v":1,"hint":"stop"` + "}`\n")
	output.WriteString("   - `{" + `"ok":false,"v":1,"error":null,"hint":"stop"` + "}`\n")
	output.WriteString("   - `{" + `"ok":false,"v":1,"error":{"code":1,"message":"failed"},"hint":"stop"` + "}`\n")
	output.WriteString("   - `{" + `"ok":false,"v":1,"error":{"code":"FAILED","message":1},"hint":"stop"` + "}`\n")
	output.WriteString("   - `{" + `"ok":false,"v":1,"error":{"code":"FAILED","message":"failed"},"hint":1` + "}`\n")
	output.WriteString("   - `{" + `"ok":false,"v":1,"error":{"code":"FAILED","message":"failed"},"hint":"stop","data":null` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":null` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":[]` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"count":null}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"count":-1}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"count":1.0}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"count":1e0}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"count":"1"}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"truncated":null}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"truncated":"false"}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"next_cursor":null}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"next_cursor":1}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"profile":null}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"profile":false}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"instance":null}` + "}`\n")
	output.WriteString("   - `{" + `"ok":true,"v":1,"data":{},"meta":{"instance":[]}` + "}`\n\n")
	output.WriteString("2. A valid v1 stdout envelope is authoritative; stderr is diagnostic only.\n")
	output.WriteString("3. If a confirmed `mutation apply` result is missing, malformed, or reports\n")
	output.WriteString("   `WRITE_OUTCOME_UNKNOWN`, never replay the mutation. Run the bounded\n")
	output.WriteString("   `mutation reconcile` flow for the same receipt. An inconclusive result is\n")
	output.WriteString("   `operator_resolution_required`, never inferred success or failure.\n\n")
	output.WriteString("## Exit codes\n\n")
	output.WriteString("Each status maps to a distinct caller recovery action.\n\n")
	output.WriteString("| Code | Name | Meaning | Caller's next move |\n")
	output.WriteString("| ---: | --- | --- | --- |\n")
	for _, info := range contract.Codes {
		_, _ = fmt.Fprintf(&output, "| %d | `%s` | %s | %s |\n", info.Code, info.Name, info.Meaning, info.NextMove)
	}
	output.WriteString("\n## Recovery rules\n\n")
	output.WriteString("- Treat `403` as permission/scope denial (exit 8), not authentication.\n")
	output.WriteString("- Treat `409` as stale state/conflict (exit 9); re-read before another write.\n")
	output.WriteString("- Follow `next_cursor` only within the caller's explicit bound.\n")
	output.WriteString("- A compiled Go runtime can exit 2 after an unrecovered panic. The process entry\n")
	output.WriteString("  must recover ordinary panics and report exit 1 so they are not mistaken for\n")
	output.WriteString("  correct usage failures.\n")
	output.WriteString("- `youtrack-agent-cli contract` exposes the same table as JSON at runtime.\n")
	return output.String()
}
